"""Tipos y columnas comunes de los modelos.
Common types and columns for the models.
"""

import uuid
from datetime import datetime
from enum import StrEnum

from sqlalchemy import DateTime, Enum, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column


def pg_enum(enum_cls: type[StrEnum], name: str) -> Enum:
    """ES: ENUM de PostgreSQL que guarda el valor ("red"), no el nombre ("RED").
    EN: PostgreSQL ENUM that stores the value ("red"), not the name ("RED").
    """
    return Enum(
        enum_cls,
        name=name,
        values_callable=lambda members: [m.value for m in members],
    )


def uuid_pk() -> Mapped[uuid.UUID]:
    """ES: Clave primaria UUID v4 generada por PostgreSQL.
    EN: UUID v4 primary key generated by PostgreSQL.
    """
    return mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )


def created_at() -> Mapped[datetime]:
    return mapped_column(
        DateTime(timezone=True), nullable=False, server_default=text("now()")
    )


# ES: Fecha con zona horaria (TIMESTAMPTZ). EN: Timezone-aware date (TIMESTAMPTZ).
